(function(){
"use strict";
const jarvis=window.JARVISBetter;
const get=id=>document.getElementById(id);
if(!jarvis||!get("jbMessages"))return;
const style=document.createElement("style");
style.textContent="#voiceSettings{margin:12px 0;background:#101c26;border:1px solid #385063;border-radius:13px;padding:13px;text-align:left}#voiceSettings details summary{font-size:13px;font-weight:750;color:#c7efac;cursor:pointer}#voiceSettings .vrRow{display:flex;flex-wrap:wrap;gap:9px;align-items:center;margin:10px 0}#voiceSettings select,#voiceSettings input{font:inherit;background:#0a1520;border:1px solid #526474;border-radius:10px;color:#eef6e8;padding:9px;min-width:0;max-width:100%}#voiceSettings button{border:1px solid #547048;border-radius:10px;background:#b8f47e;color:#132016;padding:8px 11px;font:700 12px system-ui}#vrStatus{font-size:12px;color:#bbd6bc;line-height:1.45}#vrStatus.error{color:#f2bea6}";
document.head.appendChild(style);
const div=document.createElement("div");div.id="voiceSettings";div.style.display="none";
div.innerHTML='<details><summary>🔊 Private voice engine <span id="vrBadge">(checking connection)</span></summary>'+
'<p class="jbSmall">Personal use: permitted OmniVoice when available. TrendWale commercial content: Kokoro. Both need a private model server; no subscription voice API is connected here.</p>'+
'<label class="jbLabel" for="vrPurpose">Voice usage</label><select id="vrPurpose"><option value="personal">Personal JARVIS conversation</option><option value="commercial">TrendWale commercial content</option></select>'+
'<label class="jbLabel" for="vrPreset">Voice</label><select id="vrPreset"><option value="">Automatic British male</option><option value="bm_george">Kokoro · George (British male)</option><option value="bm_lewis">Kokoro · Lewis (British male)</option></select>'+
'<label class="jbLabel" for="vrSpeed">Speed</label><input type="range" id="vrSpeed" min="0.75" max="1.30" value="1.00" step="0.05"><span id="vrSpeedValue">1.00×</span>'+
'<div class="vrRow"><button id="vrEnable" type="button">Enable natural speech</button><button id="vrSample" type="button">Try sample</button><button id="vrStop" type="button">Stop</button></div>'+
'<div id="vrStatus" role="status" aria-live="polite">Checking for a private model host...</div>'+
'<p class="jbSmall">Voices are generated by your private Python server, not by the phone voice. Until a real model server is connected, text chat remains available. OmniVoice pretrained weights are noncommercial.</p>'+
'</details>';
const target=get("jbMute")?.closest(".jbPanel");
if(target)target.appendChild(div);
const st={configured:false,enabled:false,controller:null,audio:null,url:null,checking:false};
const note=(value,error=false)=>{const el=get("vrStatus");if(el){el.textContent=value;el.classList.toggle("error",error)}};
const setVoice=(enabled)=>{
 st.enabled=enabled;
 jarvis.app.voiceOn=enabled;
 const mute=get("jbMute");if(mute)mute.textContent=enabled?"🔊 Voice on":"🔇 Voice off";
 get("vrEnable").textContent=enabled?"Disable natural speech":"Enable natural speech";
};
function stop(){
 if(st.controller){st.controller.abort();st.controller=null}
 if(st.audio){try{st.audio.pause();st.audio.currentTime=0}catch{}st.audio.src="";st.audio=null}
 if(st.url){URL.revokeObjectURL(st.url);st.url=null}
}
function setting(){
 const purpose=get("vrPurpose").value;
 const requested=get("vrPreset").value;
 if(purpose==="commercial")return {purpose,provider:"kokoro",voice:requested||"bm_george"};
 return requested?{purpose,provider:"kokoro",voice:requested}:{purpose,provider:"auto",voice:""};
}
function wav(blob){
 if(blob.type&&!blob.type.includes("wav")&&!blob.type.includes("octet-stream"))throw Error("Voice server returned the wrong audio type");
 return blob;
}
async function status(){
 if(st.checking)return;st.checking=true;
 try{
  const r=await fetch("/api/voice",{cache:"no-store"});
  const d=await r.json();
  st.configured=Boolean(d.configured);div.style.display=st.configured?"block":"none";
  get("vrBadge").textContent=st.configured?"(host configured)":"(requires model host)";
  if(!st.configured){setVoice(false);note("Speech server not yet hosted. See services/voice/README.md in your private GitHub project.");}
  else note("Model host configured. Enable natural speech and test a short sample.");
 }catch(e){st.configured=false;div.style.display="none";setVoice(false);note("Voice connection status unavailable: "+e.message,true)}
 finally{st.checking=false}
}
get("vrSpeed").oninput=()=>get("vrSpeedValue").textContent=Number(get("vrSpeed").value).toFixed(2)+"×";
get("vrPurpose").onchange=()=>{stop();note(get("vrPurpose").value==="commercial"?"Commercial voice uses Kokoro only.":"Personal chat may use OmniVoice when privately hosted.")};
get("vrPreset").onchange=stop;
get("vrStop").onclick=()=>{stop();note("Speech stopped.")};
get("vrEnable").onclick=async()=>{
 if(st.enabled){stop();setVoice(false);note("Natural speech disabled.");return}
 await status();
 if(!st.configured){note("Cannot enable: no private model server connected. I will not use robotic audio as a substitute.",true);return}
 setVoice(true);
 note("Natural speech enabled. No audio is generated until you ask JARVIS a question or test a sample.");
};
async function speak(text){
 if(!st.enabled)return false;
 if(!st.configured){note("Voice server is not configured. Text chat still works.",true);return true}
 stop();
 const controller=new AbortController();st.controller=controller;
 const opts=setting();
 note("Generating "+(opts.purpose==="commercial"?"Kokoro":"private")+" voice...");
 try{
  const owner=jarvis.token();
  const r=await fetch("/api/voice",{
   method:"POST",headers:{"Content-Type":"application/json","x-owner-token":owner},
   body:JSON.stringify({...opts,text:String(text).slice(0,850),speed:Number(get("vrSpeed").value)}),
   signal:controller.signal
  });
  if(!r.ok){
   const message=await r.json().catch(()=>({}));
   throw Error(message.error||"Speech server HTTP "+r.status);
  }
  const blob=wav(await r.blob());
  if(controller.signal.aborted)return true;
  st.url=URL.createObjectURL(blob);
  const audio=new Audio();st.audio=audio;audio.src=st.url;audio.preload="auto";
  audio.onended=()=>{if(st.audio===audio){note("Ready.");stop()}};
  audio.onerror=()=>note("Audio playback failed on this device.",true);
  await audio.play();
  note("Speaking naturally · tap Stop to interrupt.");
 }catch(e){
  if(e.name!=="AbortError")note("Natural voice unavailable: "+e.message,true);
 }
 return true;
}
get("vrSample").onclick=()=>{if(!st.enabled){note("Enable natural speech first.");return}speak("At your service, Master. I am your private JARVIS assistant.")};
get("jbClose")?.addEventListener("click",stop);
const oldMute=get("jbMute");
if(oldMute){oldMute.addEventListener("click",()=>{if(st.enabled&&jarvis.app.voiceOn===false){st.enabled=false;stop();get("vrEnable").textContent="Enable natural speech";note("Natural speech disabled.")}})}
window.JARVISExternalTTS={isEnabled:()=>st.enabled,speak,stop,status};
status();
})();